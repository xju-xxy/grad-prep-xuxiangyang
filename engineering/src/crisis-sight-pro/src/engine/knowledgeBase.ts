// 按类型命中知识库条目，未命中落回通用条目
export function lookup(disasterType: string): { key: string; entry: KbEntry } {
  const key = ALIASES[disasterType] ?? '通用'
  return { key, entry: KNOWLEDGE_BASE[key] ?? KNOWLEDGE_BASE['通用'] }
}

// 把「次生灾害」「应对要点」这种顿号/逗号分隔的字段拆成条目数组
export function splitItems(field: string): string[] {
  return field
    .split(/[、,，;；]/)
    .map((s) => s.trim())
    .filter(Boolean)
}
